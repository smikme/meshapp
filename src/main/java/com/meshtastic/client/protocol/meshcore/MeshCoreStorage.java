package com.meshtastic.client.protocol.meshcore;

import com.meshtastic.client.service.DatabaseProvider;

import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.sql.*;
import java.util.*;

/** Durable local identifiers and protocol-specific snapshots, separated from radio ACK hashes. */
// H2 schema is created at runtime and covered by database integration tests.
@SuppressWarnings({"SqlNoDataSourceInspection", "SqlResolve"})
final class MeshCoreStorage {
    private final Connection db;

    MeshCoreStorage() {
        db = DatabaseProvider.getConnection();
        if (db == null) throw new IllegalStateException("MeshCore history database unavailable");
        try (var s = db.createStatement()) {
            s.execute(
                    "CREATE TABLE IF NOT EXISTS meshcore_envelopes (owner_id VARCHAR(80) NOT NULL, message_id BIGINT NOT NULL, payload VARBINARY(176), channel_name VARCHAR(128), channel_fingerprint VARCHAR(64), PRIMARY KEY(owner_id,message_id))");
            s.execute(
                    "CREATE TABLE IF NOT EXISTS meshcore_attempts (owner_id VARCHAR(80) NOT NULL, message_id BIGINT NOT NULL, attempt INT NOT NULL, started_at BIGINT NOT NULL, status VARCHAR(20), ack_hash BIGINT, timeout_ms BIGINT, error VARCHAR(1000), PRIMARY KEY(owner_id,message_id,attempt))");
            s.execute(
                    "CREATE TABLE IF NOT EXISTS meshcore_message_ids (packet_id INT GENERATED BY DEFAULT AS IDENTITY (START WITH 1500000000) PRIMARY KEY, owner_id VARCHAR(80) NOT NULL, identity VARCHAR(100) NOT NULL, UNIQUE(owner_id, identity))");
            s.execute(
                    "CREATE TABLE IF NOT EXISTS meshcore_events (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, owner_id VARCHAR(80) NOT NULL, received_at BIGINT NOT NULL, type INT NOT NULL, payload VARBINARY(176) NOT NULL)");
            s.execute(
                    "CREATE TABLE IF NOT EXISTS meshcore_contacts (owner_id VARCHAR(80) NOT NULL, public_key VARCHAR(64) NOT NULL, payload VARBINARY(176) NOT NULL, PRIMARY KEY(owner_id, public_key))");
            s.execute(
                    "CREATE TABLE IF NOT EXISTS meshcore_aliases (owner_id VARCHAR(80) NOT NULL, alias VARCHAR(80) NOT NULL, full_id VARCHAR(80) NOT NULL, PRIMARY KEY(owner_id, alias))");
        } catch (SQLException e) {
            throw failure(e);
        }
    }

    synchronized int messageId(String owner, String identity) {
        try {
            try (var insert =
                    db.prepareStatement(
                            "INSERT INTO meshcore_message_ids(owner_id,identity) SELECT ?,? WHERE NOT EXISTS (SELECT 1 FROM meshcore_message_ids WHERE owner_id=? AND identity=?)")) {
                insert.setString(1, owner);
                insert.setString(2, identity);
                insert.setString(3, owner);
                insert.setString(4, identity);
                try {
                    insert.executeUpdate();
                } catch (SQLException e) {
                    if (!"23505".equals(e.getSQLState())) throw e;
                }
            }
            try (var select =
                    db.prepareStatement(
                            "SELECT packet_id FROM meshcore_message_ids WHERE owner_id=? AND identity=?")) {
                select.setString(1, owner);
                select.setString(2, identity);
                try (var r = select.executeQuery()) {
                    if (r.next()) return r.getInt(1);
                }
            }
            throw new IllegalStateException("Missing MeshCore message identity");
        } catch (SQLException e) {
            throw failure(e);
        }
    }

    synchronized void saveContact(String owner, byte[] payload) {
        try (var s =
                db.prepareStatement(
                        "MERGE INTO meshcore_contacts(owner_id,public_key,payload) KEY(owner_id,public_key) VALUES(?,?,?)")) {
            s.setString(1, owner);
            s.setString(2, HexFormat.of().formatHex(payload, 1, 33));
            s.setBytes(3, payload);
            s.executeUpdate();
        } catch (SQLException e) {
            throw failure(e);
        }
    }

    synchronized List<byte[]> contacts(String owner) {
        var result = new ArrayList<byte[]>();
        try (var s =
                db.prepareStatement("SELECT payload FROM meshcore_contacts WHERE owner_id=?")) {
            s.setString(1, owner);
            try (var r = s.executeQuery()) {
                while (r.next()) result.add(r.getBytes(1));
            }
        } catch (SQLException e) {
            throw failure(e);
        }
        return result;
    }

    synchronized void deleteContact(String owner, String fullKey) {
        try (var s =
                db.prepareStatement(
                        "DELETE FROM meshcore_contacts WHERE owner_id=? AND public_key=?")) {
            s.setString(1, owner);
            s.setString(2, fullKey);
            s.executeUpdate();
        } catch (SQLException e) {
            throw failure(e);
        }
    }

    /** Migrates legacy short identifiers only while their binding is unambiguous. */
    synchronized void bindAlias(String owner, String fullId, boolean localOwner) {
        if (fullId.length() != 67) return;
        String alias = fullId.substring(0, 15);
        try {
            try (var s =
                    db.prepareStatement(
                            "SELECT full_id FROM meshcore_aliases WHERE owner_id=? AND alias=?")) {
                s.setString(1, owner);
                s.setString(2, alias);
                try (var r = s.executeQuery()) {
                    if (r.next()) {
                        // A colliding prefix must not migrate another contact's history. Full
                        // identities remain separate.
                        if (!r.getString(1).equals(fullId)) return;
                    }
                }
            }
            // A short contact is only meaningful within the owner's network/history.
            for (String table :
                    List.of(
                            "messages",
                            "message_reactions",
                            "chat_threads",
                            "chat_read_counts",
                            "traceroute_results")) {
                Set<String> columns = new HashSet<>();
                try (var r =
                        db.getMetaData()
                                .getColumns(null, "PUBLIC", table.toUpperCase(Locale.ROOT), "%")) {
                    while (r.next()) columns.add(r.getString("COLUMN_NAME"));
                }
                for (String column :
                        List.of(
                                "OWNER_NODE_ID",
                                "FROM_NODE_ID",
                                "TO_NODE_ID",
                                "CHAT_KEY",
                                "TARGET_NODE_ID",
                                "RESPONSE_FROM_NODE_ID")) {
                    if (!columns.contains(column)
                            || (!localOwner && column.equals("OWNER_NODE_ID"))) continue;
                    String filter =
                            localOwner
                                    ? " AND (OWNER_NODE_ID=? OR OWNER_NODE_ID=?)"
                                    : " AND OWNER_NODE_ID=?";
                    try (var s =
                            db.prepareStatement(
                                    "UPDATE "
                                            + table
                                            + " SET "
                                            + column
                                            + "=? WHERE "
                                            + column
                                            + "=?"
                                            + filter)) {
                        s.setString(1, fullId);
                        s.setString(2, alias);
                        s.setString(3, owner);
                        if (localOwner) s.setString(4, alias);
                        try {
                            s.executeUpdate();
                        } catch (SQLException collision) {
                            if (!"23505".equals(collision.getSQLState())) throw collision;
                        }
                    }
                    if (!localOwner) {
                        try (var s =
                                db.prepareStatement(
                                        "UPDATE "
                                                + table
                                                + " SET "
                                                + column
                                                + "=? WHERE "
                                                + column
                                                + "=? AND OWNER_NODE_ID=?")) {
                            s.setString(1, fullId);
                            s.setString(2, "mc:pending:" + alias.substring(3));
                            s.setString(3, owner);
                            try {
                                s.executeUpdate();
                            } catch (SQLException collision) {
                                if (!"23505".equals(collision.getSQLState())) throw collision;
                            }
                        }
                    }
                }
            }
            try (var s =
                    db.prepareStatement(
                            "MERGE INTO meshcore_aliases KEY(owner_id,alias) VALUES(?,?,?)")) {
                s.setString(1, owner);
                s.setString(2, alias);
                s.setString(3, fullId);
                s.executeUpdate();
            }
        } catch (SQLException e) {
            throw failure(e);
        }
    }

    synchronized void saveEnvelope(String owner, long row, byte[] packet, MeshCoreChannel channel) {
        try (var s =
                db.prepareStatement(
                        "MERGE INTO meshcore_envelopes KEY(owner_id,message_id) VALUES(?,?,?,?,?)")) {
            s.setString(1, owner);
            s.setLong(2, row);
            s.setBytes(3, packet);
            s.setString(4, channel == null ? null : channel.name());
            s.setString(5, channel == null ? null : digest(channel.secret()));
            s.executeUpdate();
        } catch (SQLException e) {
            throw failure(e);
        }
    }

    synchronized com.google.gson.JsonObject messageDetails(String owner, long row) {
        var result = new com.google.gson.JsonObject();
        try (var s =
                db.prepareStatement(
                        "SELECT payload,channel_name,channel_fingerprint FROM meshcore_envelopes WHERE owner_id=? AND message_id=?")) {
            s.setString(1, owner);
            s.setLong(2, row);
            try (var r = s.executeQuery()) {
                if (r.next()) {
                    result.addProperty("payloadHex", HexFormat.of().formatHex(r.getBytes(1)));
                    result.addProperty("channelName", r.getString(2));
                    result.addProperty("channelFingerprint", r.getString(3));
                }
            }
        } catch (SQLException e) {
            throw failure(e);
        }
        return result;
    }

    synchronized int lastAttempt(String owner, long row) {
        try (var s =
                db.prepareStatement(
                        "SELECT MAX(attempt) FROM meshcore_attempts WHERE owner_id=? AND message_id=?")) {
            s.setString(1, owner);
            s.setLong(2, row);
            try (var r = s.executeQuery()) {
                r.next();
                int attempt = r.getInt(1);
                return r.wasNull() ? -1 : attempt;
            }
        } catch (SQLException e) {
            throw failure(e);
        }
    }

    synchronized void beginAttempt(String owner, long row, int attempt) {
        try (var s =
                db.prepareStatement(
                        "INSERT INTO meshcore_attempts(owner_id,message_id,attempt,started_at,status) VALUES(?,?,?,?, 'SENDING')")) {
            s.setString(1, owner);
            s.setLong(2, row);
            s.setInt(3, attempt);
            s.setLong(4, System.currentTimeMillis());
            s.executeUpdate();
        } catch (SQLException e) {
            throw failure(e);
        }
    }

    synchronized void attemptStatus(String owner, long row, String status, String error) {
        try (var s =
                db.prepareStatement(
                        "UPDATE meshcore_attempts SET status=?,error=? WHERE owner_id=? AND message_id=? AND attempt=(SELECT MAX(attempt) FROM meshcore_attempts WHERE owner_id=? AND message_id=?)")) {
            s.setString(1, status);
            s.setString(2, error);
            s.setString(3, owner);
            s.setLong(4, row);
            s.setString(5, owner);
            s.setLong(6, row);
            s.executeUpdate();
        } catch (SQLException e) {
            throw failure(e);
        }
    }

    synchronized void attemptAck(String owner, long row, long hash, long timeout) {
        try (var s =
                db.prepareStatement(
                        "UPDATE meshcore_attempts SET ack_hash=?,timeout_ms=? WHERE owner_id=? AND message_id=? AND attempt=(SELECT MAX(attempt) FROM meshcore_attempts WHERE owner_id=? AND message_id=?)")) {
            s.setLong(1, hash);
            s.setLong(2, timeout);
            s.setString(3, owner);
            s.setLong(4, row);
            s.setString(5, owner);
            s.setLong(6, row);
            s.executeUpdate();
        } catch (SQLException e) {
            throw failure(e);
        }
    }

    synchronized List<MeshCoreSendAttempt> attempts(String owner, long row) {
        List<MeshCoreSendAttempt> result = new ArrayList<>();
        try (var s =
                db.prepareStatement(
                        "SELECT attempt,started_at,status,ack_hash,timeout_ms,error FROM meshcore_attempts WHERE owner_id=? AND message_id=? ORDER BY attempt")) {
            s.setString(1, owner);
            s.setLong(2, row);
            try (var r = s.executeQuery()) {
                while (r.next())
                    result.add(
                            new MeshCoreSendAttempt(
                                    r.getInt(1),
                                    r.getLong(2),
                                    r.getString(3),
                                    (Long) r.getObject(4),
                                    (Long) r.getObject(5),
                                    r.getString(6)));
            }
        } catch (SQLException e) {
            throw failure(e);
        }
        return List.copyOf(result);
    }

    synchronized void saveEvent(String owner, byte[] packet) {
        try (var s =
                db.prepareStatement(
                        "INSERT INTO meshcore_events(owner_id,received_at,type,payload) VALUES(?,?,?,?)")) {
            s.setString(1, owner);
            s.setLong(2, System.currentTimeMillis());
            s.setInt(3, packet[0] & 255);
            s.setBytes(4, packet);
            s.executeUpdate();
            try (var trim =
                    db.prepareStatement(
                            "DELETE FROM meshcore_events WHERE owner_id=? AND id NOT IN (SELECT id FROM meshcore_events WHERE owner_id=? ORDER BY id DESC LIMIT 1000)")) {
                trim.setString(1, owner);
                trim.setString(2, owner);
                trim.executeUpdate();
            }
        } catch (SQLException e) {
            throw failure(e);
        }
    }

    synchronized List<MeshCoreEvent> events(String owner) {
        var events = new ArrayList<MeshCoreEvent>();
        try (var s =
                db.prepareStatement(
                        "SELECT received_at,type,payload FROM meshcore_events WHERE owner_id=? ORDER BY id DESC LIMIT 100")) {
            s.setString(1, owner);
            try (var r = s.executeQuery()) {
                while (r.next())
                    events.add(new MeshCoreEvent(r.getLong(1), r.getInt(2), r.getBytes(3)));
            }
        } catch (SQLException e) {
            throw failure(e);
        }
        return events;
    }

    static String digest(byte[] data) {
        try {
            return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(data));
        } catch (java.security.NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }

    static String digest(String text) {
        return digest(text.getBytes(StandardCharsets.UTF_8));
    }

    private static IllegalStateException failure(SQLException e) {
        return new IllegalStateException("MeshCore storage operation failed", e);
    }
}
